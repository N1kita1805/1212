<?php
$tickets = [
    'Билет 1 Москва-Челябинск',
    'Билет 2 Москва-Владивосток',
    'Билет 3 Москва-Санкт_Петербург',
    'Билет 4 Москва-Новосибирск',
    'Билет 5 Москва-Казань',
    'Билет 6 Москва-Сочи',
    'Билет 7 Москва-Екатеринбург',
    'Билет 8 Москва-Самара'
];
$passengers = [];
$people = ['Александр', 'Екатерина', 'Дмитрий', 'Анна', 'Иван', 'Мария', 'Сергей', 'Ольга', 'Никита', 'Елена'];
foreach ($people as $name) {
    echo "Здравствуйте, $name!<br>";
    if (!$tickets) {
        echo "Билетов нет.<br><br>";
        continue;
    }
    echo "Доступные билеты: " . implode(", ", $tickets) . "<br>";
    $chosen = array_shift($tickets);
    $passengers[] = "$name - $chosen";
    echo "$name купил: $chosen<br><br>";
}
echo "Пассажиры:<br>" . implode("<br>", $passengers);